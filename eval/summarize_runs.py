"""Summarize real agentfw runs into evaluation tables (no model calls).

Reads the audit logs (<AGENTFW_HOME>/logs/<project>/run-*/audit.jsonl) and a handoffs
folder, and writes eval/results.md: every agent run, rejected documents and why,
guardrail denials, tool use per role, and the human decisions taken at the gates.

    .venv/bin/python eval/summarize_runs.py ridexpress --handoffs-dir .work/handoffs/ridexpress
"""
from __future__ import annotations

import argparse
import collections
import json
import os
import re
from pathlib import Path

import yaml


def load_events(logs: Path) -> list[dict]:
    events = []
    for f in sorted(logs.glob("run-*/audit.jsonl")):
        events += [json.loads(line) for line in f.read_text().splitlines() if line.strip()]
    return events


def short(reason: str) -> list[str]:
    """The individual problems in a handoff rejection, with paths and run-specific text trimmed."""
    if reason.startswith("document:") and "is not of type 'object'" in reason or reason.startswith("document: '{"):
        return ["document sent as a JSON string instead of an object (argument format)"]
    lines = [ln.strip()[2:] for ln in reason.splitlines() if ln.strip().startswith("- ")]
    return [re.sub(r"\s+", " ", ln)[:160] for ln in (lines or [reason.splitlines()[0][:160]])]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("project")
    ap.add_argument("--handoffs-dir", required=True)
    ap.add_argument("--out", default=str(Path(__file__).with_name("results.md")))
    a = ap.parse_args()

    home = Path(os.environ.get("AGENTFW_HOME", Path.home() / ".agentfw"))
    events = load_events(home / "logs" / a.project)
    by_run = collections.defaultdict(list)
    for e in events:
        by_run[e["run_id"]].append(e)

    out = [f"# Evaluation: real runs on `{a.project}`", "",
           "Generated by `eval/summarize_runs.py` from the audit logs and handoff documents. "
           "Every number below is counted from those files; nothing is estimated.", ""]

    # ---- Agent runs ----------------------------------------------------------------
    out += ["## Agent runs", "",
            "| Run | Role | Model | Goal | Stop | Model calls | Tokens | Writes ok / rejected | Documents |",
            "|---|---|---|---|---|---|---|---|---|"]
    role_totals = collections.defaultdict(lambda: collections.Counter())
    tool_use = collections.defaultdict(collections.Counter)
    rejections = collections.Counter()
    agent_runs = 0
    for run_id, evs in by_run.items():
        start = next((e for e in evs if e["event"] == "agent_start"), None)
        if not start:
            continue
        agent_runs += 1
        end = next((e for e in evs if e["event"] == "agent_end"), None)
        writes = [e for e in evs if e["event"] == "tool_call" and e["tool"] == "handoff.write"]
        ok = sum(e["outcome"] == "ok" for e in writes)
        for e in writes:
            if e["outcome"] != "ok":
                for p in short(e.get("reason", "")):
                    rejections[p] += 1
        for e in evs:
            if e["event"] == "tool_call":
                tool_use[start["role"]][e["tool"]] += 1
        stop = end["stop_reason"] if end else "no end (crashed or interrupted)"
        tokens = end["tokens"]["total"] if end else 0
        calls = end["model_calls"] if end else 0
        docs = ", ".join(end["outputs"]) if end and end["outputs"] else "-"
        model = start["model"].split("/", 1)[-1]
        out.append(f"| {run_id[4:]} | {start['role']} | {model} | {', '.join(start['expect'] or [])} | {stop} "
                   f"| {calls} | {tokens:,} | {ok} / {len(writes) - ok} | {docs} |")
        t = role_totals[start["role"]]
        t["runs"] += 1
        t["finished"] += stop == "finished"
        t["tokens"] += tokens
        t["calls"] += calls
        t["docs"] += len(end["outputs"]) if end else 0
    out += ["", f"{agent_runs} agent runs.", ""]

    out += ["## Totals per role", "", "| Role | Runs | Finished | Documents | Model calls | Tokens |",
            "|---|---|---|---|---|---|"]
    for role, t in role_totals.items():
        out.append(f"| {role} | {t['runs']} | {t['finished']} | {t['docs']} | {t['calls']} | {t['tokens']:,} |")

    out += ["", "## Documents rejected by the code checks", "",
            "Each rejection went back to the agent with this message; the agent then fixed and resent the document "
            "or ran out of budget.", "", "| Times | Problem |", "|---|---|"]
    out += [f"| {n} | {p.replace('|', '/')} |" for p, n in rejections.most_common()]

    # ---- Guardrails ---------------------------------------------------------------
    denied = [e for e in events if e["event"] == "tool_call" and e["outcome"] == "denied"]
    out += ["", "## Guardrail denials", "", "Tool calls the permission guard refused (path, command or host rules).", "",
            "| Role | Tool | Reason |", "|---|---|---|"]
    for e in denied:
        reason = re.sub(r"/\S*/RideXpress/", ".../RideXpress/", e.get("reason", ""))
        out.append(f"| {e['role']} | {e['tool']} | {reason[:200].replace('|', '/')} |")

    # ---- Tool use -----------------------------------------------------------------
    out += ["", "## Tool use per role (agent runs and manual calls)", ""]
    for role, c in tool_use.items():
        out.append(f"- **{role}:** " + ", ".join(f"{t} {n}" for t, n in c.most_common()))

    # ---- Human decisions ----------------------------------------------------------
    docs = [yaml.safe_load(p.read_text()) for p in sorted(Path(a.handoffs_dir).glob("*.yaml"))]
    out += ["", "## Documents and human decisions", "", "| Document | Type | Written by | Status | Decision | Comment |",
            "|---|---|---|---|---|---|"]
    for d in docs:
        ap_ = d.get("approval", {})
        comment = (ap_.get("comment") or "").replace("\n", " ").replace("|", "/")
        out.append(f"| {d['id']} | {d['type']} | {d['created_by']['actor']} | {d['status']} "
                   f"| {ap_.get('decision', '-')} | {comment[:240]} |")

    Path(a.out).write_text("\n".join(out) + "\n")
    print(f"wrote {a.out}: {agent_runs} agent runs, {sum(rejections.values())} rejected problems, "
          f"{len(denied)} denials, {len(docs)} documents")


if __name__ == "__main__":
    main()
